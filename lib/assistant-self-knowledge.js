/**
 * One line on what is connected right now, from what the server and the app know.
 * { whatsapp: bool, computerLabel: string|null, phoneActions: bool, phoneControl: bool, phoneControlEnabled: bool, platform: string }
 */
export function selfStatusInstruction(status = {}) {
  const parts = [
    status.whatsapp ? 'WhatsApp مربوط' : 'WhatsApp غير مربوط',
    status.computerLabel ? `الكمبيوتر «${String(status.computerLabel).slice(0, 64)}» مربوط` : 'لا يوجد كمبيوتر مربوط',
    status.phoneActions ? 'إجراءات الهاتف متاحة' : 'إجراءات الهاتف غير متاحة هنا',
    status.phoneControl
      ? (status.phoneControlEnabled ? 'التحكم في التطبيقات مفعّل' : 'التحكم في التطبيقات متاح لكنه يحتاج تفعيلًا من إعدادات إمكانية الوصول')
      : 'التحكم في التطبيقات غير متاح على هذا الجهاز (أندرويد فقط)',
  ];
  return `الحالة الآن: ${parts.join('، ')}.`;
}
